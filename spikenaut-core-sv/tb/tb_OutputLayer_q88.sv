// tb_OutputLayer_q88.sv
// Canonical source: spikenaut-core-sv/tb
// Q8.8 saturation-boundary golden testbench for OutputLayer.sv's signed
// saturating accumulator.
//
// tb_OutputLayer_golden (GH#66) checks only the one-hot argmax against the
// shipped bank, which never comes near +/-128. This TB checks the exact
// class_acc words (by hierarchical reference, so the synthesized module needs
// no debug port) as well as the argmax, on cases built to land on, step past,
// and back off from 0x7FFF / 0x8000, plus cases where per-step saturation and
// a single final clamp disagree.
//
// Every weight, bitmap and expectation comes from
// spikenaut-core-sv/mem/golden/q88b_out_*.mem, generated by
// scripts/gen_golden_q88_boundary.py from a bit-exact Python model built on
// scripts/q88.py. The real WeightRam is reloaded per case from that image.
//
// Run from the repo root (golden paths are repo-root relative).
// Stimulus and checks run on negedge clk, matching every other core TB.

`timescale 1ns/1ps

module tb_OutputLayer_q88 #(
    parameter string WEIGHTS_FILE = "spikenaut-core-sv/mem/golden/q88b_out_weights.mem",
    parameter string BITMAP_FILE  = "spikenaut-core-sv/mem/golden/q88b_out_bitmap.mem",
    parameter string SCORES_FILE  = "spikenaut-core-sv/mem/golden/q88b_out_exp_scores.mem",
    parameter string RESULT_FILE  = "spikenaut-core-sv/mem/golden/q88b_out_exp_result.mem",
    parameter string COUNT_FILE   = "spikenaut-core-sv/mem/golden/q88b_out_count.mem"
);

    localparam int DATA_WIDTH        = 16;
    localparam int NUM_NEURONS       = 16;
    localparam int NUM_CLASSES       = 3;
    localparam int PAIRS             = NUM_NEURONS * NUM_CLASSES;
    localparam int WEIGHT_ADDR_WIDTH = 6;
    localparam int CLK_PERIOD        = 10;
    localparam int MAX_CASES         = 64;
    localparam int SWEEP_TIMEOUT     = 80;

    logic                         clk;
    logic                         rst_n;
    logic                         spike_valid;
    logic [NUM_NEURONS-1:0]       spike_bitmap;
    logic [DATA_WIDTH-1:0]        weight_dout;
    logic [WEIGHT_ADDR_WIDTH-1:0] weight_addr;
    logic [NUM_CLASSES-1:0]       result;
    logic                         done;

    int errors = 0;
    int n_cases;

    logic [15:0] weights_vec [0:MAX_CASES*PAIRS-1];
    logic [15:0] bitmap_vec  [0:MAX_CASES-1];
    logic [15:0] scores_vec  [0:MAX_CASES*NUM_CLASSES-1];
    logic [15:0] result_vec  [0:MAX_CASES-1];
    logic [15:0] count_vec   [0:0];

    WeightRam #(
        .ADDR_WIDTH (WEIGHT_ADDR_WIDTH),
        .DATA_WIDTH (DATA_WIDTH),
        .INIT_FILE  ("NONE")
    ) u_wram (
        .clk   (clk),
        .rst_n (rst_n),
        .we    (1'b0),
        .addr  (weight_addr),
        .din   ('0),
        .dout  (weight_dout)
    );

    OutputLayer #(
        .DATA_WIDTH        (DATA_WIDTH),
        .NUM_NEURONS       (NUM_NEURONS),
        .NUM_CLASSES       (NUM_CLASSES),
        .WEIGHT_ADDR_WIDTH (WEIGHT_ADDR_WIDTH)
    ) dut (
        .clk          (clk),
        .rst_n        (rst_n),
        .spike_valid  (spike_valid),
        .spike_bitmap (spike_bitmap),
        .weight_dout  (weight_dout),
        .weight_addr  (weight_addr),
        .result       (result),
        .done         (done)
    );

    initial clk = 1'b0;
    always #(CLK_PERIOD/2) clk = ~clk;

    task automatic require_file(input string path);
        int fd;
        fd = $fopen(path, "r");
        if (fd == 0)
            $fatal(1, "TB_OUTPUTLAYER_Q88: cannot open '%s' (run from the repo root)", path);
        $fclose(fd);
    endtask

    initial begin
        require_file(WEIGHTS_FILE);
        require_file(BITMAP_FILE);
        require_file(SCORES_FILE);
        require_file(RESULT_FILE);
        require_file(COUNT_FILE);

        $readmemh(WEIGHTS_FILE, weights_vec);
        $readmemh(BITMAP_FILE,  bitmap_vec);
        $readmemh(SCORES_FILE,  scores_vec);
        $readmemh(RESULT_FILE,  result_vec);
        $readmemh(COUNT_FILE,   count_vec);

        n_cases = int'(count_vec[0]);
        if (n_cases <= 0 || n_cases > MAX_CASES)
            $fatal(1, "TB_OUTPUTLAYER_Q88: case count %0d out of range 1..%0d", n_cases, MAX_CASES);

        begin : vacuity_guard
            automatic bit saw_max = 1'b0;
            automatic bit saw_min = 1'b0;
            for (int i = 0; i < n_cases * NUM_CLASSES; i++) begin
                if (scores_vec[i] == 16'h7FFF) saw_max = 1'b1;
                if (scores_vec[i] == 16'h8000) saw_min = 1'b1;
            end
            if (!saw_max || !saw_min)
                $fatal(1, "TB_OUTPUTLAYER_Q88: golden images look empty or unloaded");
        end

        $display("TB_OUTPUTLAYER_Q88: replaying %0d accumulator boundary cases", n_cases);

        rst_n        = 1'b0;
        spike_valid  = 1'b0;
        spike_bitmap = '0;
        repeat (2) @(negedge clk);
        rst_n = 1'b1;
        @(negedge clk);

        for (int i = 0; i < n_cases; i++) begin
            int unsigned waited;

            for (int a = 0; a < PAIRS; a++)
                u_wram.mem[a] = weights_vec[i * PAIRS + a];
            spike_bitmap = bitmap_vec[i][NUM_NEURONS-1:0];
            @(negedge clk);
            spike_valid = 1'b1;
            @(negedge clk);
            spike_valid = 1'b0;
            waited = 0;
            while (done !== 1'b1 && waited < SWEEP_TIMEOUT) begin
                @(negedge clk);
                waited++;
            end

            if (done !== 1'b1) begin
                errors++;
                $display("FAIL case %0d: sweep did not finish within %0d cycles", i, SWEEP_TIMEOUT);
                continue;
            end

            for (int c = 0; c < NUM_CLASSES; c++) begin
                if (dut.class_acc[c] !== scores_vec[i * NUM_CLASSES + c]) begin
                    errors++;
                    $display("FAIL case %0d (bitmap %04h) class %0d: class_acc %04h, golden %04h",
                             i, bitmap_vec[i], c, dut.class_acc[c], scores_vec[i * NUM_CLASSES + c]);
                end
            end
            if (result !== result_vec[i][NUM_CLASSES-1:0]) begin
                errors++;
                $display("FAIL case %0d (bitmap %04h): result %b, golden %b",
                         i, bitmap_vec[i], result, result_vec[i][NUM_CLASSES-1:0]);
            end
        end

        if (errors == 0) begin
            $display("TB_OUTPUTLAYER_Q88: ALL %0d BOUNDARY CASES MATCHED", n_cases);
            $finish;
        end else begin
            $display("TB_OUTPUTLAYER_Q88: %0d MISMATCH(ES)", errors);
            $display("  Case indices map to 'output_layer' entries in spikenaut-core-sv/mem/golden/q88_boundary_vectors.json.");
            $fatal(1, "TB_OUTPUTLAYER_Q88: testbench FAILED");
        end
    end

endmodule
